import { stripFence } from "../TaskBoard/refinePrompts";

/**
 * 系統連線定時任務「目標」的 AI 潤飾。這段文字到點會原封不動交給一個無人值守的 AI，
 * 它只能用 sys_* 工具操作那個網頁系統，沒有人可以追問，所以要寫成一次就能照做的指令。
 */
export const GOAL_REFINE_SYSTEM = [
  "你要把使用者草擬的內容，改寫成一份「在某個外部網頁系統上自動執行的任務目標」。",
  "這份目標會在固定時間交給一個 AI 去操作那個網頁系統（點選、填寫、查詢、送出），執行時沒有人在旁邊可以追問，所以必須一次說清楚。",
  "",
  "改寫原則：",
  "- 保留使用者的原意與所有具體資訊（欄位名稱、數值、信箱、網址、日期、專有名詞），不要發明使用者沒說的需求、帳號、欄位或步驟。",
  "- 先用一句話寫這次要達成什麼，再用簡短條列寫要做的事。",
  "- 明確分開「只查看」與「會改動資料」的步驟；使用者沒要求的新增、修改、刪除、送出一律不要加。",
  "- 寫清楚做完要回報什麼（例如筆數、結果、有沒有成功）；使用者沒說的就只寫從原文看得出來的。",
  "- 遇到登入失效、找不到欄位或頁面不是預期的樣子時，要停下來回報，不要亂試——這一點寫成一行，方便 AI 照做。",
  "- 每次到點都會重新執行，不要寫「今天」「這次」這類只對單次成立的字眼，除非是任務本身的日期條件。",
  "- 精簡：能用幾行講完的就不要拉長。",
  "- 用使用者草稿的語言書寫。只輸出目標本身：不要包成程式碼區塊，不要開場白或結語。",
].join("\n");

export function buildGoalRefineMessage(draft: string, systemName: string): string {
  return `要操作的系統：${systemName}\n使用者草擬的任務目標：\n${draft}`;
}

/** 去掉模型可能包的程式碼區塊與頭尾空白；整份是空的回傳 null。 */
export function parseGoalReply(reply: string): string | null {
  const text = stripFence(reply.trim()).trim();
  return text || null;
}
